import { test, expect } from '@playwright/test';

test('task, project, and goal workflow persists and renders safely', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Today.' })).toBeVisible();
  await page.getByRole('button', { name: 'Try sample tasks' }).click();
  await expect(page.getByText('Sketch ideas for the homepage', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'New project', exact: true }).first().click();
  await page.getByLabel('Project name').fill('Test project');
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button', { name: 'My goals' }).click();
  await page.getByRole('button', { name: 'New goal', exact: true }).click();
  await page.getByLabel('Your goal').fill('Ship the project');
  await page.getByLabel('Why it matters').fill('A clear milestone.');
  await page.getByRole('button', { name: 'Create goal', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button', { name: 'Add task', exact: true }).first().click();
  const taskTitle = '<img src=x onerror=alert(1)> Write 100%';
  await page.getByLabel('What would you like to do?').fill(taskTitle);
  await page.getByLabel('Notes', { exact: false }).fill('Saved notes');
  await page.getByLabel('Project', { exact: true }).selectOption({ label: 'Test project' });
  await page.getByLabel('Linked goal').selectOption({ label: 'Ship the project' });
  await page.getByLabel('Priority', { exact: true }).selectOption('high');
  await page.getByRole('dialog').getByRole('button', { name: 'Add task' }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button', { name: /Test project/ }).click();
  await expect(page.getByText(taskTitle, { exact: true })).toBeVisible();
  await expect(page.locator('.task-row img')).toHaveCount(0);
  await page.reload();
  await expect(page.getByText(taskTitle, { exact: true })).toBeVisible();
  await page.getByRole('button', { name: `Edit ${taskTitle}`, exact: true }).click();
  await expect(page.getByLabel('Notes')).toHaveValue('Saved notes');
  await page.getByLabel('What would you like to do?').fill('Revised 100% task');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button', { name: 'Complete Revised 100% task', exact: true }).click();
  await expect(page.getByText('Revised 100% task', { exact: true })).not.toBeVisible();
  await page.getByRole('button', { name: 'My goals' }).click();
  await expect(page.locator('.goal-card').filter({ hasText: 'Ship the project' })).toContainText('100%');
  await page.getByRole('button', { name: /Find a task/ }).click();
  await page.getByPlaceholder('Search task titles and notes…').fill('100%');
  await expect(page.getByText('Revised 100% task', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit Revised 100% task', exact: true }).click();
  await page.getByRole('button', { name: 'Delete task', exact: true }).click();
  await page.getByRole('button', { name: 'Delete task', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByText('Revised 100% task', { exact: true })).not.toBeVisible();
  expect(errors).toEqual([]);
});


test('API rejects invalid requests, protects conflicts, and exports persisted data', async ({ request }) => {
  const invalid = await request.post('/api/tasks', { data: { title: 'Invalid', due_date: '2026-02-30' } });
  expect(invalid.status()).toBe(400);
  const crossSite = await request.post('/api/tasks', { data: { title: 'Blocked' }, headers: { Origin: 'https://example.com' } });
  expect(crossSite.status()).toBe(403);
  const created = await request.post('/api/tasks', { data: { title: 'API durability', priority: 'high' } });
  expect(created.status()).toBe(201); const task = await created.json();
  const update = await request.patch(`/api/tasks/${task.id}`, { data: { revision: task.revision, title: 'Updated via API' } });
  expect(update.status()).toBe(200);
  const stale = await request.patch(`/api/tasks/${task.id}`, { data: { revision: task.revision, title: 'Stale edit' } });
  expect(stale.status()).toBe(409);
  const exported = await request.get('/api/export'); expect(exported.status()).toBe(200);
  expect((await exported.json()).tasks.some(t => t.title === 'Updated via API')).toBe(true);
  const oversized = await request.post('/api/tasks', { data: { title: 'Too much', notes: 'x'.repeat(40000) } });
  expect(oversized.status()).toBe(413);
});
